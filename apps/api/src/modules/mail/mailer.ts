import { Schema, model } from 'mongoose';
import type { AppConfig } from '../../config/app-config.js';

// The mail boundary (docs/architecture/ACCOUNT_EMAIL.md). The platform asks for a templated message
// to one address; the configured Mailer decides what happens:
// - 'none' (default): nothing is sent (no email provider is chosen yet, B7) — flows still answer
//   the same, non-enumerating way;
// - 'dev_sink': messages are stored in a development-only collection that platform administrators
//   can read in the operator console. Refused in production. No real message ever leaves.
// A real provider implements the same interface once chosen (E2).

export const MAIL_TEMPLATES = ['email_verification', 'password_reset', 'invitation'] as const;
export type MailTemplate = (typeof MAIL_TEMPLATES)[number];
export type MailMessage = { to: string; template: MailTemplate; language: 'ar' | 'en'; vars: Record<string, string> };

export interface Mailer {
  readonly name: 'none' | 'dev_sink';
  send(message: MailMessage): Promise<void>;
}

export interface DevMail {
  to: string;
  template: MailTemplate;
  language: 'ar' | 'en';
  subject: string;
  text: string;
  createdAt: Date;
}
const devMailSchema = new Schema<DevMail>(
  {
    to: { type: String, required: true },
    template: { type: String, enum: MAIL_TEMPLATES, required: true },
    language: { type: String, enum: ['ar', 'en'], required: true },
    subject: { type: String, required: true },
    text: { type: String, required: true },
  },
  { collection: 'dev_mail_sink', timestamps: { createdAt: true, updatedAt: false } },
);
devMailSchema.index({ createdAt: -1 });
// Development messages carry live tokens; they disappear after a day.
devMailSchema.index({ createdAt: 1 }, { expireAfterSeconds: 24 * 3600 });
export const DevMailModel = model<DevMail>('DevMail', devMailSchema);

const link = (config: AppConfig, path: string) => `${config.appBaseUrl}${path}`;

/** Plain-text bilingual templates. Variables are generated by the server, never user free text. */
export function renderMail(config: AppConfig, { template, language, vars }: MailMessage): { subject: string; text: string } {
  const ar = language === 'ar';
  if (template === 'password_reset') {
    return {
      subject: ar ? 'إعادة تعيين كلمة المرور — raclinic' : 'Reset your password — raclinic',
      text: ar
        ? `طلب أحدهم إعادة تعيين كلمة مرور حسابك في raclinic.\nلإعادة التعيين افتح الرابط التالي خلال ساعة واحدة (يُستخدم مرة واحدة):\n${link(config, `/reset-password?token=${vars.token}`)}\nإذا لم تطلب ذلك فتجاهل هذه الرسالة؛ كلمة مرورك لم تتغير.`
        : `Someone asked to reset the password of your raclinic account.\nOpen this link within one hour to choose a new password (it works once):\n${link(config, `/reset-password?token=${vars.token}`)}\nIf you did not ask for this, ignore this message; your password has not changed.`,
    };
  }
  if (template === 'email_verification') {
    return {
      subject: ar ? 'تأكيد البريد الإلكتروني — raclinic' : 'Confirm your email — raclinic',
      text: ar
        ? `لتأكيد بريدك الإلكتروني في raclinic افتح الرابط التالي خلال 24 ساعة (يُستخدم مرة واحدة):\n${link(config, `/verify-email?token=${vars.token}`)}`
        : `To confirm your email address for raclinic, open this link within 24 hours (it works once):\n${link(config, `/verify-email?token=${vars.token}`)}`,
    };
  }
  return {
    subject: ar ? `دعوة للانضمام إلى ${vars.organization} — raclinic` : `Invitation to join ${vars.organization} — raclinic`,
    text: ar
      ? `دُعيت للانضمام إلى «${vars.organization}» على raclinic.\nافتح الرابط التالي خلال 7 أيام، ثم سجّل الدخول أو أنشئ حسابًا بهذا البريد نفسه:\n${link(config, `/invitations/accept?token=${vars.token}`)}`
      : `You have been invited to join "${vars.organization}" on raclinic.\nOpen this link within 7 days, then sign in or create an account with this same email address:\n${link(config, `/invitations/accept?token=${vars.token}`)}`,
  };
}

export function createMailer(config: AppConfig): Mailer {
  if (config.mailProvider === 'dev_sink') {
    return {
      name: 'dev_sink',
      async send(message) {
        const { subject, text } = renderMail(config, message);
        await DevMailModel.create({ to: message.to, template: message.template, language: message.language, subject, text });
      },
    };
  }
  return { name: 'none', send: async () => {} };
}
